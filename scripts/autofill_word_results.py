"""Append real experiment result tables to a manuscript DOCX.

This does not invent numbers. It reads CSVs generated by run_full.py and appends
an automatically generated results appendix. You can then manually move the tables
into the main Results section before submission.

Usage:
    python scripts/autofill_word_results.py \
      --manuscript RankPSM_Q4_SCI_Manuscript_v2_2_PreSubmission.docx \
      --results-dir results --exports-dir paper_exports \
      --out RankPSM_Q4_SCI_Manuscript_v3_0_WithRealResults.docx
"""
from pathlib import Path
import argparse, pandas as pd
from docx import Document
from docx.shared import Inches, Pt


def add_df_table(doc, title, df, max_rows=80):
    doc.add_heading(title, level=2)
    if len(df)>max_rows:
        doc.add_paragraph(f"Showing first {max_rows} rows out of {len(df)}. Full CSV is provided in the experiment package.")
        df=df.head(max_rows)
    table=doc.add_table(rows=1, cols=len(df.columns))
    table.style='Table Grid'
    hdr=table.rows[0].cells
    for i,c in enumerate(df.columns): hdr[i].text=str(c)
    for _, row in df.iterrows():
        cells=table.add_row().cells
        for i,c in enumerate(df.columns):
            v=row[c]
            if isinstance(v,float): v=f"{v:.4f}"
            cells[i].text=str(v)
    doc.add_paragraph()


def main():
    ap=argparse.ArgumentParser()
    ap.add_argument('--manuscript', required=True)
    ap.add_argument('--results-dir', default='results')
    ap.add_argument('--exports-dir', default='paper_exports')
    ap.add_argument('--out', required=True)
    args=ap.parse_args()
    doc=Document(args.manuscript)
    doc.add_page_break()
    doc.add_heading('Automatically Inserted Real Experiment Results', level=1)
    doc.add_paragraph('This appendix was generated from actual experiment CSV outputs. Replace the placeholder [TBD]/[AUTO] values in the main Results section only after verifying these tables and figures.')
    paths=[
        ('Main weighted Spearman table', Path(args.exports_dir)/'table_main_weighted_spearman.csv'),
        ('Security overestimation table', Path(args.exports_dir)/'table_security_overestimation.csv'),
        ('Ablation summary table', Path(args.exports_dir)/'table_ablation.csv'),
        ('Generalization gap table', Path(args.exports_dir)/'table_generalization_gap.csv'),
        ('All metrics', Path(args.results_dir)/'all_metrics.csv'),
        ('Bootstrap confidence intervals', Path(args.results_dir)/'bootstrap_ci.csv'),
    ]
    for title,p in paths:
        if p.exists():
            df=pd.read_csv(p)
            add_df_table(doc,title,df)
        else:
            doc.add_paragraph(f'Missing: {p}')
    fig_dir=Path('figures')
    for img in ['weighted_spearman.png','wsor20.png']:
        p=fig_dir/img
        if p.exists():
            doc.add_heading(img, level=2)
            doc.add_picture(str(p), width=Inches(6.1))
    doc.save(args.out)
    print(f'Wrote {args.out}')
if __name__=='__main__': main()
